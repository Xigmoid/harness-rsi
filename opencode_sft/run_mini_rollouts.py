def load_manifest(registry: Path) -> list[dict[str, Any]]:
    path = registry / "manifest.jsonl"
    entries = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            entries.append(json.loads(line))
    return entries


def load_manifest_file(path: Path) -> list[dict[str, Any]]:
    """A manifest that is not the registry's default one.

    The two harnesses each get half of every dataset, and the half is
    written as its own manifest (``manifest-mini.jsonl``,
    ``manifest-opencode.jsonl``) by ``opencode_sft/split_tasks.py``.  The
    driver then runs one of them, so the split is honoured by the task list
    rather than by a filter applied afterwards.
    """
    entries = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            entries.append(json.loads(line))
    return entries


def is_local_endpoint(url: str) -> bool:
    """Is this endpoint the recording proxy on this host?

    The proxy is the only thing that may hold a real API key, so a key file
    is only acceptable when the endpoint is the proxy: the proxy injects the
    key on the way out and the job file keeps the placeholder.
    """
    host = url.split("//", 1)[-1].split("/", 1)[0]
    host = host.rsplit("@", 1)[-1]
    if host.startswith("["):
        host = host[1:].split("]", 1)[0]
    else:
        host = host.split(":", 1)[0]
    return host in {
        "localhost",
        "127.0.0.1",
        "0.0.0.0",
        "::1",
        "host.docker.internal",
    }


def load_ledger(path: Path) -> dict[str, dict[str, Any]]:
    """The finished trials, keyed by registry name.

    A record with ``ok: false`` is **not** counted as done: a trial that
    failed has to be retried.
    """
    done: dict[str, dict[str, Any]] = {}
    if not path.exists():
        return done
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not record.get("ok"):
            continue
        done[record["registry_name"]] = record
    return done


def load_attempts(path: Path) -> dict[str, int]:
    """How many times each registry task has been attempted, failed or not."""
    attempts: dict[str, int] = {}
    if not path.exists():
        return attempts
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        name = record.get("registry_name")
        if name:
            attempts[name] = attempts.get(name, 0) + 1
    return attempts


def check_toolchain() -> str | None:
    """Is the toolchain bundle intact?

    The bundle is bind-mounted into every trial and the adapter's fast path
    tests ``/root/.local/bin/mini-swe-agent`` inside the container.  If the
    bundle is damaged, that test fails and *every* trial falls back to the
    four-minute install -- which, before the install was redirected away from
    the mount, also rewrote the bundle and broke it further.

    The bundle's shims are symlinks to absolute paths **inside** the
    container (``/root/.local/...``), so on the host they are dangling by
    design: the check has to be "does the link exist", not "does it resolve".

    Returns None when the bundle is usable, or a message describing what is
    wrong.
    """
    bundle = TOOLCHAIN_DIR
    if not bundle.is_dir():
        return f"the bundle directory {bundle} does not exist"
    shim = bundle / "bin" / "mini-swe-agent"
    if not os.path.lexists(shim):
        return f"{shim} is missing -- the bundle was damaged by a trial"
    tool_python = bundle / "share" / "uv" / "tools" / "mini-swe-agent" / "bin" / "python"
    if not os.path.lexists(tool_python):
        return (
            f"{tool_python} is missing -- the tool environment was removed by "
            "a trial that ran the fallback install"
        )
    uv_python = bundle / "share" / "uv" / "python"
    if not uv_python.is_dir():
        return f"{uv_python} is missing -- the bundle has no managed python"
    return None


def prune_docker() -> None:
    """Remove the containers and the networks the finished trials left behind.

    Every trial gets its own compose project, and every project its own
    bridge network.  A trial that died -- or a job that was cancelled --
    leaks its network, and leaked networks are not reusable: Docker hands
    them out of a fixed address pool that is only sixteen networks wide.
    Once the pool is empty every new trial dies with::

        failed to create network ...: all predefined address pools have been
        fully subnetted

    which looks like an agent failure but is not one.

    The pool is not widened (``default-address-pools`` in
    ``~/.docker/daemon.json`` stops Docker Desktop's engine from starting at
    all on this host), so the leak is removed at the other end instead: every
    trial joins one shared network (see ``shared_network.py``), and the
    per-trial networks that leaked are removed by name.
    """
    subprocess.run(
        ["docker", "container", "prune", "-f"],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    remove_leaked_networks()
    ensure_shared_network()


def network_count() -> int:
    result = subprocess.run(
        ["docker", "network", "ls", "-q"],
        capture_output=True,
        text=True,
        check=False,
    )
    return len([line for line in result.stdout.splitlines() if line.strip()])


def shard_of(name: str, shards: int) -> int:
    digest = hashlib.sha256(name.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big") % shards


def load_mini_config(path: Path) -> dict[str, Any]:
    config = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(config, dict):
        raise SystemExit(f"{path}: the mini config did not parse into a mapping")
    for section in ("agent", "model", "environment"):
        if section not in config:
            raise SystemExit(f"{path}: the mini config has no '{section}' section")
    return config


def write_batch_job(
    path: Path,
    batch: int,
    jobs_dir: Path,
    concurrency: int,
    registry: Path,
    entries: list[dict[str, Any]],
    config: dict[str, Any],
    timeout: int,
    verifier_enabled: bool = False,
    model_name: str = MODEL_NAME,
) -> None:
    by_family: dict[str, list[str]] = defaultdict(list)
    for entry in entries:
        by_family[entry["family"]].append(entry["task"])

    lines = []
    for family in sorted(by_family):
        lines.append(f"- path: {registry / family}")
        lines.append("  task_names:")
        for name in sorted(by_family[family]):
            lines.append(f"  - {name}")

    config_text = yaml.safe_dump(config, sort_keys=False, allow_unicode=True, width=4096)
    config_lines = "\n".join("      " + line for line in config_text.splitlines())

    path.write_text(
        JOB_TEMPLATE.format(
            batch=batch,
            jobs_dir=jobs_dir,
            concurrency=concurrency,
            timeout=timeout,
            model_name=model_name,
            toolchain_dir=TOOLCHAIN_DIR,
            toolchain_target=TOOLCHAIN_TARGET,
            config=config_lines,
            datasets="\n".join(lines),
            verifier_disabled="false" if verifier_enabled else "true",
        ),
        encoding="utf-8",
    )


def harvest(batch_dir: Path) -> list[dict[str, Any]]:
    """The per-trial results of a finished batch."""
    results = []
    for result_file in sorted(batch_dir.rglob("result.json")):
        trial_dir = result_file.parent
        try:
            payload = json.loads(result_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        exception = payload.get("exception_info")
        results.append(
            {
                "trial_dir": str(trial_dir),
                "trial_name": trial_dir.name,
                "task_name": payload.get("task_name"),
                "started_at": payload.get("started_at"),
                "finished_at": payload.get("finished_at"),
                "ok": exception is None,
                "exception": exception,
                "reward": read_reward(trial_dir),
            }
        )
    return results


def read_reward(trial_dir: Path) -> float | None:
    """The verifier's reward, when the verifier ran.

    Harbor's verifier writes a single float to ``verifier/reward.txt``.  The
    file is absent when the verifier is disabled, when the trial died before
    the verification phase, or when the verifier itself crashed -- all three
    are different from "the agent scored zero", so an absent file is reported
    as ``None`` and never as ``0.0``.
    """
    reward_path = trial_dir / "verifier" / "reward.txt"
    try:
        raw = reward_path.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    if not raw:
        return None
    try:
        value = float(raw)
    except ValueError:
        return None
    if value != value or value in (float("inf"), float("-inf")):
        return None
    return value


def make_record(
    entry: dict[str, Any],
    match: dict[str, Any],
    batch_number: int,
    model_name: str = MODEL_NAME,
    api_base: str = API_BASE,
) -> dict[str, Any]:
    """One ledger line for one finished trial.

    The model that produced the rollout is part of the record: the run can
    be served by more than one endpoint, and a dataset row has to be able to
    say which one wrote it.
    """
    return {
        "registry_name": entry["task"],
        "family": entry["family"],
        "dataset_rows": entry.get("source_rows", []),
        "task": entry["task"],
        "ok": match["ok"],
        "trial_dir": match["trial_dir"],
        "trial_name": match["trial_name"],
        "exception": match["exception"],
        "reward": match.get("reward"),
        "batch": batch_number,
        "model": model_name,
        "api_base": api_base,
    }


def append_records(ledger_path: Path, records: list[dict[str, Any]]) -> int:
    """Append ledger lines.  The ledger is append-only: a crash can only ever
    lose the tail, never rewrite what was already recorded."""
    if not records:
        return 0
    with ledger_path.open("a", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
        handle.flush()
        os.fsync(handle.fileno())
    return len(records)


def resync_ledger(
    run_root: Path, ledger_path: Path, family_of: dict[str, str]
) -> int:
    """Rebuild the ledger from the trial directories already on disk.

    The ledger is the source of truth for "what is done", but a run that is
    interrupted in the middle of a batch would otherwise re-run every trial of
    that batch: the batch's trials are only recorded once the whole batch
    finished.  Every finished trial leaves a ``result.json`` behind, so the
    batch directories are the real record and the ledger can be recovered
    from them.

    Only tasks that are not in the ledger at all are added, so this never
    contradicts an earlier line -- it only fills in the gap.
    """
    known: set[str] = set()
    if ledger_path.exists():
        for line in ledger_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            name = record.get("registry_name")
            if name:
                known.add(name)

    records: list[dict[str, Any]] = []
    for result_file in sorted(run_root.glob("batch-*/**/result.json")):
        trial_dir = result_file.parent
        try:
            payload = json.loads(result_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        task_name = payload.get("task_name")
        if not task_name or task_name in known:
            continue
        family = family_of.get(task_name)
        if family is None:
            continue
        exception = payload.get("exception_info")
        known.add(task_name)
        records.append(
            {
                "registry_name": task_name,
                "family": family,
                "dataset_rows": [],
                "task": task_name,
                "ok": exception is None,
                "trial_dir": str(trial_dir),
                "trial_name": trial_dir.name,
                "exception": exception,
                "reward": read_reward(trial_dir),
                "batch": _batch_of(run_root, trial_dir),
                "resynced": True,
            }
        )
    return append_records(ledger_path, records)


def _batch_of(run_root: Path, trial_dir: Path) -> int:
    """The batch number a trial directory belongs to."""
    for part in trial_dir.parts:
        if part.startswith("batch-"):
            tail = part.split("-")[-1]
            if tail.isdigit():
                return int(tail)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", default=str(HERE / "registry"))
    parser.add_argument(
        "--run-root",
        default="/private/tmp/rsi-harbor/mini-sft-full",
        help="Harbor's output directory; must be on a mountable path "
        "(on macOS: /private/tmp, not the project directory and not /tmp)",
    )
    parser.add_argument("--batch-size", type=int, default=200)
    parser.add_argument("--concurrency", type=int, default=8)
    parser.add_argument("--families", default="swesmith,issue,tezos,superuser")
    parser.add_argument("--shard", default="0/1", help="shard index/total")
    parser.add_argument("--timeout", type=int, default=1800)
    parser.add_argument(
        "--max-batches", type=int, default=0, help="stop after N batches (0 = all)"
    )
    parser.add_argument("--tasks", default="", help="comma separated registry names")
    parser.add_argument(
        "--resync-ledger",
        action="store_true",
        help="rebuild the ledger from the trial directories on disk before "
        "starting, so an interrupted batch is not run a second time",
    )
    parser.add_argument("--min-config", default=str(MINI_CONFIG))
    parser.add_argument(
        "--manifest",
        default="",
        help="run only the tasks in this manifest file, instead of the "
        "registry's manifest.jsonl.  The two harnesses each get half of "
        "every dataset, and the halves are manifest files written by "
        "opencode_sft/split_tasks.py.",
    )
    parser.add_argument(
        "--harbor",
        default=str(REPO / ".venv312" / "bin" / "harbor"),
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="only report what would be run"
    )
    parser.add_argument(
        "--shuffle-seed",
        type=int,
        default=0,
        help="shuffle the task order with this seed (0 = keep the manifest "
        "order).  The ClawGym manifest is ordered by dataset row, and the "
        "first thousands of rows are all one task family, so a run in "
        "manifest order spends its first batches on one kind of task.  A "
        "fixed seed keeps the run reproducible while making every batch a "
        "sample of the whole set.",
    )
    parser.add_argument(
        "--enable-verifier",
        action="store_true",
        help="run the task's verifier and record its reward.  The "
        "OpenThoughts re-annotation does not score; the ClawGym one does, "
        "because its tasks ship a verifier and the reward is what separates "
        "a solved task from an unsolved one.",
    )
    parser.add_argument(
        "--api-base",
        default=API_BASE,
        help="the endpoint the agent model is served from, as seen from "
        "inside the container.  The default is the GLM one; point it at "
        "the MiniMax endpoint to run the rollout against MiniMax instead.",
    )
    parser.add_argument(
        "--model-name",
        default=MODEL_NAME,
        help="the litellm model name of the agent model",
    )
    parser.add_argument(
        "--api-key",
        default="EMPTY",
        help="the API key for the endpoint.  The GLM endpoint takes no key; "
        "the MiniMax one does, and it is read from a file rather than being "
        "written into the job file.",
    )
    parser.add_argument(
        "--api-key-file",
        default="",
        help="read the API key from this file instead of from --api-key",
    )
    parser.add_argument(
        "--exclude-manifest",
        default="",
        help="a manifest whose tasks are skipped.  This is how the MiniMax "
        "share is carved out: the GLM run skips the tasks named in it and "
        "the MiniMax run runs exactly those, so the two never overlap.",
    )
    args = parser.parse_args()

    registry = Path(args.registry).resolve()
    run_root = Path(args.run_root).resolve()
    run_root.mkdir(parents=True, exist_ok=True)
    ledger_path = run_root / "progress.jsonl"
    shard_index, shard_total = (int(part) for part in args.shard.split("/"))

    if not TOOLCHAIN_DIR.exists():
        print(
            f"the toolchain bundle {TOOLCHAIN_DIR} is missing; the trials would "
            "each spend ~4 minutes installing mini-swe-agent (or fail)",
            file=sys.stderr,
        )
        return 2

    problem = check_toolchain()
    if problem:
        print(
            f"FATAL: the toolchain bundle is not usable: {problem}\n"
            "       Re-export it from the toolchain image "
            "(scripts/rebuild_toolchain_with_mcp.sh) before running the trials.",
            file=sys.stderr,
        )
        return 2

    config = load_mini_config(Path(args.min_config))
    # The model in the config file is the *default*; the command line wins,
    # because the whole point of the second provider is that the same
    # harness, the same environment and the same config produce a rollout
    # against a different model.
    config["model"]["model_name"] = args.model_name

    # The endpoint the agent really talks to is ``model.model_kwargs.api_base``:
    # the config is dumped into the job file, the job file goes into the
    # container, and that is where mini runs.  ``--api-base`` used to be
    # written to the *host* environment only, so a MiniMax run still went to
    # the GLM endpoint -- and the ledger called it MiniMax.  The data would
    # have been wrong with nothing to say so.
    model_kwargs = config["model"].setdefault("model_kwargs", {})
    model_kwargs["api_base"] = args.api_base
    model_kwargs["api_key"] = args.api_key

    api_key = args.api_key
    if args.api_key_file:
        api_key = read_key(args.api_key_file)
        print(f"using the API key from {args.api_key_file}")
        # The agent runs *inside* the container, so a variable on the host
        # never reaches it, and the only other way to hand it over is the job
        # file -- which is on disk and ends up in the trial log.  The
        # recording proxy is the way out: it injects the key on the way out
        # and the job file only ever holds the placeholder.
        if not is_local_endpoint(args.api_base):
            print(
                "FATAL: --api-key-file cannot be used with a remote endpoint.\n"
                "       The agent runs inside the container, so the key would "
                "have to be written into the job file, which is on disk.\n"
                "       Point --api-base at the recording proxy instead "
                "(http://host.docker.internal:<port>/v1): the proxy injects "
                "the key and the job file keeps the placeholder.",
                file=sys.stderr,
            )
            return 2

    if args.manifest:
        manifest_path = Path(args.manifest).resolve()
        if not manifest_path.exists():
            print(f"{manifest_path} does not exist", file=sys.stderr)
            return 2
        entries = load_manifest_file(manifest_path)
        print(f"using the manifest {manifest_path} ({len(entries)} tasks)")
    else:
        entries = load_manifest(registry)
    families = {f.strip() for f in args.families.split(",") if f.strip()}
    entries = [e for e in entries if e["family"] in families]
    if args.tasks:
        wanted = {t.strip() for t in args.tasks.split(",") if t.strip()}
        entries = [e for e in entries if e["task"] in wanted]
    if args.exclude_manifest:
        exclude_path = Path(args.exclude_manifest).resolve()
        if not exclude_path.exists():
            print(f"{exclude_path} does not exist", file=sys.stderr)
            return 2
        excluded = {e["task"] for e in load_manifest_file(exclude_path)}
        before = len(entries)
        entries = [e for e in entries if e["task"] not in excluded]
        print(
            f"excluding {len(excluded)} tasks named in {exclude_path} "
            f"({before} -> {len(entries)})"
        )
    if shard_total > 1:
        entries = [e for e in entries if shard_of(e["task"], shard_total) == shard_index]
    if args.shuffle_seed:
        import random

        random.Random(args.shuffle_seed).shuffle(entries)

    done = load_ledger(ledger_path)
    attempts = load_attempts(ledger_path)

    # A stale marker from an earlier finished run must not be mistaken for
    # this run having finished.
    (run_root / "COMPLETE").unlink(missing_ok=True)

    if args.resync_ledger:
        family_of = {e["task"]: e["family"] for e in entries}
        recovered = resync_ledger(run_root, ledger_path, family_of)
        if recovered:
            print(
                f"=== resynced {recovered} trials from disk into the ledger ===",
                flush=True,
            )
        done = load_ledger(ledger_path)
        attempts = load_attempts(ledger_path)

    pending = [e for e in entries if e["task"] not in done]

    print(
        json.dumps(
            {
                "registry": str(registry),
                "run_root": str(run_root),
                "ledger": str(ledger_path),
                "shard": f"{shard_index}/{shard_total}",
                "total": len(entries),
                "already_done": len(entries) - len(pending),
                "pending": len(pending),
                "batch_size": args.batch_size,
                "concurrency": args.concurrency,
                "model": args.model_name,
                "api_base": args.api_base,
                "protocol": config["model"]["model_class"],
                "toolchain": str(TOOLCHAIN_DIR),
            },
            indent=2,
        ),
        flush=True,
    )
    if args.dry_run:
        return 0

    # Only the batch *directories* count: the job file of a batch is named
    # "batch-NNNN.yaml" next to the directory "batch-NNNN", and a glob over
    # "batch-*" would match both and skip a number on every restart.
    batch_number = len(list(run_root.glob("batch-*"))) // 2 + 1
    existing = {
        int(p.name.split("-")[-1])
        for p in run_root.glob("batch-*")
        if p.is_dir() and p.name.split("-")[-1].isdigit()
    }
    if existing:
        batch_number = max(existing) + 1
    batches = 0
    while pending:
        if args.max_batches and batches >= args.max_batches:
            break
        batch = pending[: args.batch_size]
        pending = pending[args.batch_size :]

        batch_dir = run_root / f"batch-{batch_number:04d}"
        batch_dir.mkdir(parents=True, exist_ok=True)
        job_file = run_root / f"batch-{batch_number:04d}.yaml"
        write_batch_job(
            job_file,
            batch_number,
            batch_dir,
            args.concurrency,
            registry,
            batch,
            config,
            args.timeout,
            verifier_enabled=args.enable_verifier,
            model_name=args.model_name,
        )

        # Every trial leaks a compose network when it does not end cleanly,
        # and the leaked networks come out of a fixed address pool.  Clear
        # them before the batch, not after: the batch itself needs a few
        # networks at the same time.
        prune_docker()
        # The containers of the earlier batches of *this* run root:
        # a killed trial leaves its container running, and a running
        # container is not touched by ``docker container prune``.
        stale = remove_stale_containers(run_root, batch_dir)
        if stale:
            print(f"removed {stale} containers left by earlier batches", flush=True)
        # The Harbor job of an earlier batch of this run root does
        # not die with the driver that started it; it goes on raising
        # trials that nobody harvests, and the containers pile up.
        jobs = kill_stale_jobs(run_root)
        if jobs:
            print(f"killed {jobs} Harbor jobs left by earlier batches", flush=True)
        started = time.time()
        print(
            f"=== batch {batch_number}: {len(batch)} tasks "
            f"(-> {batch_dir}), {network_count()} networks held ===",
            flush=True,
        )
        command = [
            args.harbor,
            "job",
            "start",
            "-c",
            str(job_file),
            "-o",
            str(batch_dir),
            "--yes",
        ]
        environment = dict(os.environ)
        environment["PYTHONPATH"] = str(REPO)
        environment["OPENAI_API_KEY"] = api_key
        environment["OPENAI_BASE_URL"] = args.api_base

        # The batch is harvested while it runs, not after it: a batch of 100
        # trials takes hours, and a run that is stopped half way through must
        # not throw away the trials that already finished.  Every finished
        # trial leaves a result.json behind, so polling the batch directory
        # turns the ledger into a per-trial record instead of a per-batch one.
        entry_by_task = {e["task"]: e for e in batch}
        recorded: set[str] = set()
        written = 0

        def record_new() -> int:
            nonlocal written
            fresh = []
            for match in harvest(batch_dir):
                task_name = match.get("task_name")
                if not task_name or task_name in recorded:
                    continue
                entry = entry_by_task.get(task_name)
                if entry is None:
                    continue
                recorded.add(task_name)
                fresh.append(
                    make_record(entry, match, batch_number, args.model_name, args.api_base)
                )
            if fresh:
                append_records(ledger_path, fresh)
                for record in fresh:
                    attempts[record["task"]] = attempts.get(record["task"], 0) + 1
                written += len(fresh)
            return len(fresh)

        completed = subprocess.Popen(command, cwd=REPO, env=environment)
        while completed.poll() is None:
            time.sleep(15)
            try:
                record_new()
            except OSError:
                pass
        completed.wait()
        record_new()
        elapsed = time.time() - started

        harvested = harvest(batch_dir)
        by_task = {r["task_name"]: r for r in harvested if r.get("task_name")}
        print(
            f"=== batch {batch_number} finished in {elapsed:.0f}s: "
            f"{written}/{len(batch)} trials recorded, "
            f"harbor exit {completed.returncode} ===",
            flush=True,
        )

        # A failed task is retried in a later batch, up to a couple of extra
        # attempts.
        retry: list[dict[str, Any]] = []
        for entry in batch:
            match = by_task.get(entry["task"])
            if match is None or not match["ok"]:
                if attempts.get(entry["task"], 0) <= 2:
                    retry.append(entry)
        pending = retry + pending
        batch_number += 1
        batches += 1

    print(
        json.dumps(
            {
                "batches_run": batches,
                "ledger": str(ledger_path),
                "ledger_lines": len(load_ledger(ledger_path)),
            },
            indent=2,
        ),
        flush=True,
    )
    # The marker tells the supervisor that this stream is finished, so that
    # it does not start it again.  It is removed at the start of every run,
    # so a restart cannot mistake a stale marker for a finished stream.
    (run_root / "COMPLETE").write_text(
        f"{len(load_ledger(ledger_path))} tasks\n", encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
