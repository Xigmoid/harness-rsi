#!/usr/bin/env python3
"""Drive the mini-swe-agent re-annotation of OpenThoughts-Agent-SFT-31.6K.

This is the mini-harness twin of ``run_rollouts.py`` (which drives opencode).
Same shape -- batches, a resumable ledger, a retry pass -- but the agent is
``rsi.harbor_agent:RsiMiniSweAgent`` and the config is the frozen mini config
built by ``build_mini_config.py``.

Three things differ from the opencode driver, and each of them is a trap that
was already paid for once:

**The protocol is text, not tool calls.**
    ``model_class: litellm_textbased`` plus the frozen action regex.  The
    tool-call protocol needs the ``mcp`` package -- litellm imports its MCP
    handler as soon as ``tools`` is set -- and Harbor installs mini-swe-agent
    without it, so every request dies with ``ModuleNotFoundError: No module
    named 'mcp'`` and the run looks like a weak model rather than a missing
    dependency.

**The config is inlined into the job, and it is complete.**
    mini-swe-agent v2 treats ``-c`` as a spec list: any ``-c`` suppresses the
    packaged ``config/mini.yaml``.  The config therefore carries the system
    and instance templates itself.  It is a mapping (not a path) because
    Harbor's agent option only accepts a mapping for ``config``.

**The toolchain is bind-mounted.**
    The bundle at ``.cache/rsi-local`` is a linux/aarch64 build of
    mini-swe-agent 2.4.6; mounting it at ``/root/.local`` makes
    ``RsiMiniSweAgent`` skip the per-trial ``uv tool install`` (~4 minutes
    each).  Without the mount the job still works, just ~4 minutes slower per
    trial.

Usage::

    # a dry run first: reports what would happen, touches nothing
    python opencode_sft/run_mini_rollouts.py --dry-run

    # one small batch, to see the whole chain work
    python opencode_sft/run_mini_rollouts.py --batch-size 4 --max-batches 1

    # the full run
    python opencode_sft/run_mini_rollouts.py --batch-size 200 --concurrency 8

The ledger (``progress.jsonl``) is the source of truth for what is done, so
the driver can be stopped and restarted at any point.
"""

