"""Drive the full re-annotation in batches, and keep a resumable ledger.

A single Harbor job over 31,600 tasks would work, but it would be one
eight-day process: a laptop sleep, a Docker restart or a host reboot would
take the whole thing with it.  So the run is driven in **batches** instead --
a few hundred tasks each -- and every finished trial is written to a ledger
as soon as it lands.  The driver can be stopped and restarted at any point
and picks up where it left off.

The ledger (``progress.jsonl``) is the source of truth for what is done.  It
records, per registry task, the dataset rows it answers and where its trial
directory is, so the converter can join the rollouts back onto the published
dataset without guessing.

Usage::

    python opencode_sft/run_rollouts.py \
        --registry opencode_sft/registry \
        --run-root runs/opencode-sft-full \
        --batch-size 200 --concurrency 16

Shard it across machines with ``--shard i/n`` (the shard is a stable hash of
the registry task name, so two shards never pick the same task).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import shlex
import subprocess
import sys
import time
from collections import defaultdict
from pathlib import Path
from typing import Any

from minimax import read_key
from docker_cleanup import kill_stale_jobs, remove_stale_containers
from shared_network import ensure_shared_network, remove_leaked_networks

HERE = Path(__file__).resolve().parent
REPO = HERE.parent

#: The template of the per-batch Harbor job.  It is the production job with
#: the dataset section and the concurrency replaced; everything else -- the
#: agent, the model, the timeouts, the retry policy -- is identical, so the
#: batch is the same experiment as the full job, only smaller.
JOB_TEMPLATE = """# Generated by opencode_sft/run_rollouts.py -- batch {batch} of the
# full OpenThoughts-Agent re-annotation.  Do not edit by hand; the driver
# writes one of these per batch.
jobs_dir: {jobs_dir}
n_attempts: 1
n_concurrent_trials: {concurrency}
timeout_multiplier: 1.0

environment:
  type: docker
  delete: true
  force_build: false

verifier:
  disable: {verifier_disabled}

retry:
  max_retries: 3
  include_exceptions:
  - ApiRateLimitError
  - ApiInternalServerError
  - ApiOverloadedError
  - ApiConnectionClosedError

agents:
- import_path: rsi.opencode_agent:RsiOpenCode
  name: rsi-opencode
  model_name: {provider_id}/{model_id}
  override_timeout_sec: 1800
  override_setup_timeout_sec: 1800
  kwargs:
    version: "1.18.33"
    export_session: true
    skip_install_if_present: true
    opencode_config:
      provider:
        {provider_id}:
          npm: "@ai-sdk/openai-compatible"
          name: "RSI endpoint"
          options:
            baseURL: "{api_base}"
            apiKey: "{api_key}"
            setCacheKey: true
          models:
            {model_id}:
              name: "{model_id}"

datasets:
{datasets}
"""


def load_manifest(registry: Path) -> list[dict[str, Any]]:
    path = registry / "manifest.jsonl"
    entries = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            entries.append(json.loads(line))
    return entries


def load_manifest_file(path: Path) -> list[dict[str, Any]]:
    """A manifest that is not the registry's default one.

    The two harnesses each get half of every dataset, and the half is
    written as its own manifest (``manifest-mini.jsonl``,
    ``manifest-opencode.jsonl``) by ``opencode_sft/split_tasks.py``.  The
    driver then runs one of them, so the split is honoured by the task list
    rather than by a filter applied afterwards.
    """
    entries = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            entries.append(json.loads(line))
    return entries


def load_ledger(path: Path) -> dict[str, dict[str, Any]]:
    """The finished trials, keyed by registry name.

    A record with ``ok: false`` is **not** counted as done: a trial that
    failed has to be retried, and the driver is supposed to pick it up again
    after a restart.  Only the successful records count as finished work.
    """
    done: dict[str, dict[str, Any]] = {}
    if not path.exists():
        return done
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if not record.get("ok"):
            continue
        done[record["registry_name"]] = record
    return done


def load_attempts(path: Path) -> dict[str, int]:
    """How many times each registry task has been attempted, failed or not."""
    attempts: dict[str, int] = {}
    if not path.exists():
        return attempts
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        name = record.get("registry_name")
        if name:
            attempts[name] = attempts.get(name, 0) + 1
    return attempts


def prune_docker() -> None:
    """Remove the containers and networks the finished trials left behind.

    Harbor gives every trial its own compose project, and every project its
    own bridge network.  A trial that failed -- or a job that was cancelled --
    leaks its network, and the leaked networks are **not** reusable: Docker
    hands them out of a fixed address pool that is only sixteen networks
    wide by default.  Once that pool is empty every new trial dies with::

        failed to create network ...: all predefined address pools have
        been fully subnetted

    which looks like an agent failure but is not one.

    The pool is not widened -- ``default-address-pools`` in
    ``~/.docker/daemon.json`` stops Docker Desktop's engine from starting at
    all on this host -- so the leak is removed at the other end instead:
    every trial joins one shared network (see ``shared_network.py``), and the
    per-trial networks that leaked are removed by name.
    """
    subprocess.run(
        ["docker", "container", "prune", "-f"],
        capture_output=True,
        text=True,
        timeout=120,
        check=False,
    )
    remove_leaked_networks()
    ensure_shared_network()


def network_count() -> int:
    """How many networks Docker currently holds."""
    result = subprocess.run(
        ["docker", "network", "ls", "-q"],
        capture_output=True,
        text=True,
        check=False,
    )
    return len([line for line in result.stdout.splitlines() if line.strip()])


def shard_of(name: str, shards: int) -> int:
    digest = hashlib.sha256(name.encode("utf-8")).digest()
    return int.from_bytes(digest[:4], "big") % shards


def check_proxy(url: str) -> bool:
    result = subprocess.run(
        ["curl", "-sS", "-m", "10", "-o", "/dev/null", "-w", "%{http_code}", url],
        capture_output=True,
        text=True,
    )
    return result.stdout.strip().startswith("2")


def write_batch_job(
    path: Path,
    batch: int,
    jobs_dir: Path,
    concurrency: int,
    registry: Path,
    entries: list[dict[str, Any]],
    api_base: str = "http://host.docker.internal:8899/v1",
    api_key: str = "EMPTY",
    verifier_enabled: bool = False,
    model_id: str = "glm5.3-flash",
    provider_id: str = "rsi_glm",
) -> None:
    by_family: dict[str, list[str]] = defaultdict(list)
    for entry in entries:
        by_family[entry["family"]].append(entry["task"])

    lines = []
    for family in sorted(by_family):
        lines.append(f"- path: {registry / family}")
        lines.append("  task_names:")
        for name in sorted(by_family[family]):
            lines.append(f"  - {name}")
    path.write_text(
        JOB_TEMPLATE.format(
            batch=batch,
            jobs_dir=jobs_dir,
            concurrency=concurrency,
            datasets="\n".join(lines),
            api_base=api_base,
            api_key=api_key,
            verifier_disabled="false" if verifier_enabled else "true",
            model_id=model_id,
            provider_id=provider_id,
        ),
        encoding="utf-8",
    )


def harvest(batch_dir: Path) -> list[dict[str, Any]]:
    """The per-trial results of a finished batch."""
    results = []
    # Harbor writes its output as "<batch dir>/<timestamp>/<trial>/", so the
    # result files are two levels down.  ``rglob`` covers that layout and
    # the flat one alike.
    for result_file in sorted(batch_dir.rglob("result.json")):
        trial_dir = result_file.parent
        try:
            payload = json.loads(result_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        exception = payload.get("exception_info")
        results.append(
            {
                "trial_dir": str(trial_dir),
                "trial_name": trial_dir.name,
                # The name of the *task directory* the trial ran, which is the
                # registry name.  It is used to join the trial back to the
                # registry entry, and it is exact: the trial directory name
                # ("<task directory>__<suffix>") is ambiguous, because the
                # repeated rows of a task are named "<task>__row00042" and
                # their trial directories therefore also start with
                # "<task>__".
                "task_name": payload.get("task_name"),
                "started_at": payload.get("started_at"),
                "finished_at": payload.get("finished_at"),
                "ok": exception is None,
                "exception": exception,
                "reward": read_reward(trial_dir),
            }
        )
    return results


def read_reward(trial_dir: Path) -> float | None:
    """The verifier's reward, when the verifier ran.

    Harbor's verifier writes a single float to ``verifier/reward.txt``.  An
    absent file means the verifier was disabled, the trial died before the
    verification phase, or the verifier itself crashed -- three different
    things from "the agent scored zero", so it is reported as ``None`` and
    never as ``0.0``.
    """
    reward_path = trial_dir / "verifier" / "reward.txt"
    try:
        raw = reward_path.read_text(encoding="utf-8").strip()
    except OSError:
        return None
    if not raw:
        return None
    try:
        value = float(raw)
    except ValueError:
        return None
    if value != value or value in (float("inf"), float("-inf")):
        return None
    return value


def resync_ledger(
    run_root: Path, ledger_path: Path, family_of: dict[str, str]
) -> int:
    """Rebuild the ledger from the trial directories already on disk.

    The ledger is the source of truth for "what is done", but the trials of
    a batch are only recorded once the whole batch finished.  A run that is
    interrupted -- or that is restarted on purpose, to change the concurrency
    -- would otherwise run every trial of that batch again, which is hours
    of work thrown away.

    Every finished trial leaves a ``result.json`` behind, so the batch
    directories are the real record and the ledger can be recovered from
    them.  Only tasks that are not in the ledger at all are added, so this
    never contradicts an earlier line -- it only fills in the gap.
    """
    known: set[str] = set()
    if ledger_path.exists():
        for line in ledger_path.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            name = record.get("registry_name")
            if name:
                known.add(name)

    records: list[dict[str, Any]] = []
    for result_file in sorted(run_root.glob("batch-*/**/result.json")):
        trial_dir = result_file.parent
        try:
            payload = json.loads(result_file.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        task_name = payload.get("task_name")
        if not task_name or task_name in known:
            continue
        family = family_of.get(task_name)
        if family is None:
            continue
        exception = payload.get("exception_info")
        known.add(task_name)
        records.append(
            {
                "registry_name": task_name,
                "family": family,
                "dataset_rows": [],
                "task": task_name,
                "ok": exception is None,
                "trial_dir": str(trial_dir),
                "trial_name": trial_dir.name,
                "exception": exception,
                "reward": read_reward(trial_dir),
                "batch": _batch_of(run_root, trial_dir),
                "resynced": True,
            }
        )
    if not records:
        return 0
    with ledger_path.open("a", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    return len(records)


def _batch_of(run_root: Path, trial_dir: Path) -> int:
    """The batch number a trial directory belongs to."""
    for part in trial_dir.parts:
        if part.startswith("batch-"):
            try:
                return int(part.split("-", 1)[1])
            except ValueError:
                return 0
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--registry", default=str(HERE / "registry"))
    parser.add_argument("--run-root", default=str(REPO / "runs" / "opencode-sft-full"))
    parser.add_argument("--batch-size", type=int, default=200)
    parser.add_argument("--concurrency", type=int, default=16)
    parser.add_argument("--families", default="swesmith,issue,tezos,superuser")
    parser.add_argument("--shard", default="0/1", help="shard index/total")
    parser.add_argument(
        "--max-batches", type=int, default=0, help="stop after N batches (0 = all)"
    )
    parser.add_argument("--proxy-check-url", default="http://127.0.0.1:8899/v1/models")
    parser.add_argument(
        "--harbor",
        default=str(REPO / ".venv312" / "bin" / "harbor"),
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="only report what would be run"
    )
    parser.add_argument(
        "--resync-ledger",
        action="store_true",
        help="rebuild the ledger from the trial directories already on disk "
        "before starting.  A batch is only recorded once it has finished, so "
        "without this a restart re-runs every trial of the interrupted "
        "batch.",
    )
    parser.add_argument(
        "--shuffle-seed",
        type=int,
        default=0,
        help="shuffle the task order with this seed (0 = keep the manifest "
        "order).  The seed is fixed, so a restart picks up the same order "
        "and the run is reproducible.",
    )
    parser.add_argument(
        "--manifest",
        default="",
        help="run only the tasks in this manifest file, instead of the "
        "registry's manifest.jsonl.  The two harnesses each get half of "
        "every dataset, and the halves are manifest files written by "
        "opencode_sft/split_tasks.py.",
    )
    parser.add_argument(
        "--api-base",
        default="http://host.docker.internal:8899/v1",
        help="the endpoint opencode talks to, from inside the container.  "
        "The default is the recording proxy; a production run points it "
        "straight at the endpoint, because the proxy writes every request "
        "body to disk and a full run is tens of gigabytes of it.",
    )
    parser.add_argument("--api-key", default="EMPTY")
    parser.add_argument(
        "--api-key-file",
        default="",
        help="read the API key from this file instead of from --api-key",
    )
    parser.add_argument(
        "--model-id",
        default="glm5.3-flash",
        help="the model id the opencode provider offers.  The MiniMax "
        "endpoint is reached with --model-id MiniMax-M3.1-Flash.",
    )
    parser.add_argument(
        "--provider-id",
        default="rsi_glm",
        help="the name of the opencode provider; it ends up in the "
        "dataset's model field, so it says which endpoint answered.",
    )
    parser.add_argument(
        "--exclude-manifest",
        default="",
        help="a manifest whose tasks are skipped.  This is how the MiniMax "
        "share is carved out: the GLM run skips the tasks named in it and "
        "the MiniMax run runs exactly those, so the two never overlap.",
    )
    parser.add_argument(
        "--enable-verifier",
        action="store_true",
        help="run the task's verifier and record its reward.  The "
        "OpenThoughts re-annotation does not score; the ClawGym one does, "
        "because its tasks ship a verifier and the reward is what separates "
        "a solved task from an unsolved one.",
    )
    args = parser.parse_args()

    api_key = args.api_key
    if args.api_key_file:
        api_key = read_key(args.api_key_file)
        print(f"using the API key from {args.api_key_file}")

    registry = Path(args.registry).resolve()
    run_root = Path(args.run_root).resolve()
    run_root.mkdir(parents=True, exist_ok=True)
    ledger_path = run_root / "progress.jsonl"
    shard_index, shard_total = (int(part) for part in args.shard.split("/"))

    if args.manifest:
        manifest_path = Path(args.manifest).resolve()
        if not manifest_path.exists():
            print(f"{manifest_path} does not exist", file=sys.stderr)
            return 2
        entries = []
        for line in manifest_path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                entries.append(json.loads(line))
        print(f"using the manifest {manifest_path} ({len(entries)} tasks)")
    else:
        entries = load_manifest(registry)
    families = {f.strip() for f in args.families.split(",") if f.strip()}
    entries = [e for e in entries if e["family"] in families]
    if args.exclude_manifest:
        exclude_path = Path(args.exclude_manifest).resolve()
        if not exclude_path.exists():
            print(f"{exclude_path} does not exist", file=sys.stderr)
            return 2
        excluded = {e["task"] for e in load_manifest_file(exclude_path)}
        before = len(entries)
        entries = [e for e in entries if e["task"] not in excluded]
        print(
            f"excluding {len(excluded)} tasks named in {exclude_path} "
            f"({before} -> {len(entries)})"
        )
    if shard_total > 1:
        entries = [e for e in entries if shard_of(e["task"], shard_total) == shard_index]
    if args.shuffle_seed:
        # The task order is shuffled with a fixed seed, so that a restart
        # picks up the same order and the run is reproducible.  The shuffle
        # happens *after* the shard and the exclusions, so every stream
        # sees its own tasks in a stable order.
        random.Random(args.shuffle_seed).shuffle(entries)

    if args.resync_ledger:
        family_of = {e["task"]: e["family"] for e in entries}
        added = resync_ledger(run_root, ledger_path, family_of)
        print(f"resynced the ledger: {added} trials recovered from disk")

    # A stale marker from an earlier finished run must not be mistaken for
    # this run having finished.
    (run_root / "COMPLETE").unlink(missing_ok=True)

    done = load_ledger(ledger_path)
    attempts = load_attempts(ledger_path)
    pending = [e for e in entries if e["task"] not in done]
    print(
        json.dumps(
            {
                "registry": str(registry),
                "run_root": str(run_root),
                "shard": f"{shard_index}/{shard_total}",
                "total": len(entries),
                "already_done": len(entries) - len(pending),
                "pending": len(pending),
                "batch_size": args.batch_size,
                "concurrency": args.concurrency,
            },
            indent=2,
        ),
        flush=True,
    )
    if args.dry_run:
        return 0

    batch_number = len(list(run_root.glob("batch-*"))) + 1
    batches = 0
    while pending:
        if args.max_batches and batches >= args.max_batches:
            break
        batch = pending[: args.batch_size]
        pending = pending[args.batch_size :]

        if not check_proxy(args.proxy_check_url):
            print(
                f"the recording proxy is not answering on {args.proxy_check_url}; "
                "start it before running the batch",
                file=sys.stderr,
                flush=True,
            )
            return 2

        batch_dir = run_root / f"batch-{batch_number:04d}"
        batch_dir.mkdir(parents=True, exist_ok=True)
        job_file = run_root / f"batch-{batch_number:04d}.yaml"
        write_batch_job(
            job_file,
            batch_number,
            batch_dir,
            args.concurrency,
            registry,
            batch,
            api_base=args.api_base,
            api_key=api_key,
            verifier_enabled=args.enable_verifier,
            model_id=args.model_id,
            provider_id=args.provider_id,
        )

        # Every trial leaks a compose network when it does not end cleanly,
        # and the leaked networks come out of a fixed address pool.  Clear
        # them before the batch, not after: the batch itself needs a few
        # networks at the same time.
        prune_docker()
        # The containers of the earlier batches of *this* run root:
        # a killed trial leaves its container running, and a running
        # container is not touched by ``docker container prune``.
        stale = remove_stale_containers(run_root, batch_dir)
        if stale:
            print(f"removed {stale} containers left by earlier batches", flush=True)
        # The Harbor job of an earlier batch of this run root does
        # not die with the driver that started it; it goes on raising
        # trials that nobody harvests, and the containers pile up.
        jobs = kill_stale_jobs(run_root)
        if jobs:
            print(f"killed {jobs} Harbor jobs left by earlier batches", flush=True)
        started = time.time()
        print(
            f"=== batch {batch_number}: {len(batch)} tasks "
            f"(-> {batch_dir}), {network_count()} networks held ===",
            flush=True,
        )
        command = [
            args.harbor,
            "job",
            "start",
            "-c",
            str(job_file),
            "-o",
            str(batch_dir),
            "--yes",
        ]
        environment = dict(os.environ)
        environment["PYTHONPATH"] = str(REPO)
        completed = subprocess.run(command, cwd=REPO, env=environment)
        elapsed = time.time() - started

        # Harvest whatever landed, successful or not.
        harvested = harvest(batch_dir)
        by_task = {r["task_name"]: r for r in harvested if r.get("task_name")}
        written = 0
        with ledger_path.open("a", encoding="utf-8") as handle:
            for entry in batch:
                # The join is on the task *directory* name, which Harbor
                # records in result.json as "task_name".  Matching on the
                # trial directory name instead would be ambiguous, because
                # the repeated rows of a task are named "<task>__row00042"
                # and their trial directories start with "<task>__" too.
                match = by_task.get(entry["task"])
                if match is None:
                    continue
                record = {
                    "registry_name": entry["task"],
                    "family": entry["family"],
                    "dataset_rows": entry.get("source_rows", []),
                    "task": entry["task"],
                    "ok": match["ok"],
                    "trial_dir": match["trial_dir"],
                    "trial_name": match["trial_name"],
                    "exception": match["exception"],
                    "reward": match.get("reward"),
                    "batch": batch_number,
                    # The endpoint that answered is part of the record: the
                    # run can be served by more than one model, and a dataset
                    # row has to be able to say which one wrote it.
                    "model": args.model_id,
                    "provider": args.provider_id,
                    "api_base": args.api_base,
                }
                handle.write(json.dumps(record, ensure_ascii=False) + "\n")
                attempts[entry["task"]] = attempts.get(entry["task"], 0) + 1
                written += 1
        print(
            f"=== batch {batch_number} finished in {elapsed:.0f}s: "
            f"{written}/{len(batch)} trials recorded, "
            f"harbor exit {completed.returncode} ===",
            flush=True,
        )

        # A failed task is retried in a later batch, up to the job's own
        # retry policy plus a couple of extra attempts.
        retry: list[dict[str, Any]] = []
        for entry in batch:
            match = by_task.get(entry["task"])
            if match is None or not match["ok"]:
                if attempts.get(entry["task"], 0) <= 2:
                    retry.append(entry)
        pending = retry + pending
        batch_number += 1
        batches += 1

    print(
        json.dumps(
            {
                "batches_run": batches,
                "ledger": str(ledger_path),
                "ledger_lines": len(load_ledger(ledger_path)),
            },
            indent=2,
        ),
        flush=True,
    )
    # The marker tells the supervisor that this stream is finished, so that
    # it does not start it again.  It is removed at the start of every run,
    # so a restart cannot mistake a stale marker for a finished stream.
    (run_root / "COMPLETE").write_text(
        f"{len(load_ledger(ledger_path))} tasks\n", encoding="utf-8"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
